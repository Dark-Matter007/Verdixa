#!/usr/bin/env python3
"""Generate repository benchmark documentation from raw JSON only."""
from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "benchmarks" / "results"


def load(label: str, concurrency: int) -> dict:
    return json.loads((RESULTS / label / f"library-c{concurrency}.json").read_text(encoding="utf-8"))


def pct_change(old: float, new: float) -> float:
    return (new - old) * 100 / old


def rows() -> list[dict]:
    output = []
    for concurrency in (1, 4, 8):
        baseline, optimized = load("baseline", concurrency), load("optimized", concurrency)
        base, final = baseline["results"], optimized["results"]
        output.append({
            "concurrency": concurrency,
            "baseline": base,
            "optimized": final,
            "rps_change": pct_change(base["throughput_rps"], final["throughput_rps"]),
            "p95_reduction": -pct_change(base["latency_ms"]["p95"], final["latency_ms"]["p95"]),
        })
    return output


def performance_markdown(values: list[dict]) -> str:
    table = ["| Concurrent clients | Baseline RPS | Optimized RPS | Baseline p50 / p95 / p99 (ms) | Optimized p50 / p95 / p99 (ms) | Error rate |",
             "| ---: | ---: | ---: | --- | --- | ---: |"]
    for item in values:
        base, final = item["baseline"], item["optimized"]
        b, o = base["latency_ms"], final["latency_ms"]
        table.append(f"| {item['concurrency']} | {base['throughput_rps']:.3f} | {final['throughput_rps']:.3f} | "
                     f"{b['p50']:.3f} / {b['p95']:.3f} / {b['p99']:.3f} | {o['p50']:.3f} / {o['p95']:.3f} / {o['p99']:.3f} | "
                     f"{base['error_rate_percent']:.4f}% → {final['error_rate_percent']:.4f}% |")
    comparison = ["| Concurrent clients | Throughput change | p95 reduction |",
                  "| ---: | ---: | ---: |"]
    for item in values:
        comparison.append(f"| {item['concurrency']} | {item['rps_change']:+.2f}% | {item['p95_reduction']:.2f}% |")
    return "\n".join(table) + "\n\n" + "\n".join(comparison)


def replace_marked(path: Path, start: str, end: str, content: str) -> None:
    text = path.read_text(encoding="utf-8")
    before, marker, after = text.partition(start)
    if not marker:
        raise RuntimeError(f"Missing start marker in {path}")
    _, end_marker, tail = after.partition(end)
    if not end_marker:
        raise RuntimeError(f"Missing end marker in {path}")
    path.write_text(before + start + "\n" + content.rstrip() + "\n" + end + tail, encoding="utf-8")


def main() -> None:
    values = rows()
    environment = json.loads((RESULTS / "baseline" / "environment.json").read_text(encoding="utf-8"))
    performance = performance_markdown(values)
    summary = {
        "schema_version": 1,
        "environment": environment,
        "workload": load("baseline", 1)["workload"],
        "comparisons": [{"concurrency": x["concurrency"], "throughput_change_percent": round(x["rps_change"], 2),
                         "p95_reduction_percent": round(x["p95_reduction"], 2)} for x in values],
    }
    (RESULTS / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    report = "# Benchmark Summary\n\nGenerated by `python benchmarks/generate_report.py`; do not edit measured values manually.\n\n" + performance + "\n"
    (RESULTS / "REPORT.md").write_text(report, encoding="utf-8")

    environment_line = (f"Windows ({environment['os']}); {environment['cpu_logical_processors']} logical processors; "
                        f"{environment['java']}; {environment['python']}; {environment['database']}. "
                        "Total system RAM was unavailable to the restricted local shell.")
    readme = f"""## Performance & Evaluation

> All values in this section are generated from committed raw JSON by `python benchmarks/generate_report.py`.

### Test Environment

{environment_line}

### Benchmark Methodology

The measured production read path is authenticated `GET /api/problems/library?size=100`. Each clean run starts the `benchmark` Spring profile with an in-memory H2 database seeded with 1 user, 100 active problems, and 1,000 submissions. Each level has a 10-second warm-up and 20-second measurement window. This is a local H2 result, not a MySQL, Docker, or multi-host claim. Raw inputs are [baseline results](benchmarks/results/baseline/) and [optimized results](benchmarks/results/optimized/).

### Scale Test and Performance Results

{performance}

### Baseline vs Optimized

The optimization replaces per-problem submission-row loading in the library response with one grouped aggregate query. It preserves the response fields while avoiding repeated database round trips. The largest tested level was 8 concurrent clients; it completed without request errors in both passes. No saturation point above 8 clients was measured, so none is claimed.

### Reliability Testing

The local automated checks cover unauthenticated protected access, malformed login JSON, and invalid credentials; their exact observed statuses are in [reliability.json](benchmarks/results/reliability.json). Redis, queues, workers, and an external database are not part of this repository's local architecture, so cache/queue/database-restart metrics are not applicable to this run.

### Reproducing the Benchmark

See [benchmarks/README.md](benchmarks/README.md). Run `powershell -ExecutionPolicy Bypass -File benchmarks/run_local.ps1 -Label baseline`, apply/verify the target change, run the identical command with `-Label optimized`, then run `python benchmarks/generate_report.py`.
"""
    replace_marked(ROOT / "README.md", "<!-- BENCHMARK_RESULTS:START -->", "<!-- BENCHMARK_RESULTS:END -->", readme)
    c8 = values[-1]
    b, o = c8["baseline"], c8["optimized"]
    resume = f"""# Verified Resume Metrics

Generated from `benchmarks/results/**/*.json` by `python benchmarks/generate_report.py`.

- Improved authenticated problem-library throughput by {c8['rps_change']:.2f}% ({b['throughput_rps']:.3f} → {o['throughput_rps']:.3f} requests/s) at 8 concurrent local clients by replacing per-problem submission loading with grouped aggregation.
- Reduced problem-library p95 latency by {c8['p95_reduction']:.2f}% ({b['latency_ms']['p95']:.3f} ms → {o['latency_ms']['p95']:.3f} ms) at 8 concurrent local clients on the reproducible H2 workload.
- Sustained {o['throughput_rps']:.3f} requests/s with 0.0000% request errors at the highest tested level of 8 concurrent local clients after the query optimization.
"""
    (ROOT / "RESUME_METRICS.md").write_text(resume, encoding="utf-8")


if __name__ == "__main__":
    main()
